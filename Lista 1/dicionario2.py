# Criando um dicionário de uma pessoa

pessoa = {
    'nome': 'Taissa',
    'sexo': 'Feminino',
    'idade': 34,
    'altura': 1.53,
    'peso': 54,
}

# Acessando valores
print(pessoa['nome'])
print(pessoa['idade'])
print(pessoa['altura'])
print(pessoa['peso'])

# Alterando um valor
pessoa['idade'] = 55
print(pessoa)

# Adicionar uma nova chave-valor

pessoa['cor'] = 'azul'
print(pessoa)





